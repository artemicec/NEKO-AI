// Подготовка текста к озвучке.
// (В прошлой версии использовался \p{Emoji} — это свойство включает ЦИФРЫ, «#» и «*»,
//  поэтому цифры из речи пропадали. Здесь используется Extended_Pictographic.)

/** Убирает всё, что не стоит произносить вслух */
export function cleanForSpeech(text: string): string {
  return text
    // **жирный** → просто текст (до того, как вырезаем *действия*)
    .replace(/\*\*([^*\n]+)\*\*/g, '$1')
    // действия в звёздочках: *виляет хвостом* — не озвучиваем целиком
    .replace(/(?<!\*)\*(?!\*)[^*\n]{1,120}(?<!\*)\*(?!\*)/g, ' ')
    // markdown-ссылки [текст](url) → текст
    .replace(/\[([^\]]+)\]\((?:https?:\/\/)[^)]+\)/g, '$1')
    // голые ссылки
    .replace(/https?:\/\/\S+/g, ' ')
    // код и разметка
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/[`_~#>*]+/g, ' ')
    // эмодзи (цифры не трогаем)
    .replace(/[\p{Extended_Pictographic}‍️\u{1F3FB}-\u{1F3FF}]/gu, '')
    // тильда-протяжка «Ня~»
    .replace(/\s+/g, ' ')
    .trim()
}

/** Есть ли в строке что-то, что можно произнести (буквы или цифры) */
export function hasSpeakable(text: string): boolean {
  return /[\p{L}\p{N}]/u.test(text)
}
