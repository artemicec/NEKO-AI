// src/shared/services/webRouter.ts
//
// Когда приложению нужен интернет. Три пути, и ни один не тратит лишний запрос к модели:
//   1. Явная просьба: «найди в интернете…», «загугли…», «что в википедии про…» — работает всегда (если интернет не выключен).
//   2. Эвристика по форме вопроса: «кто такой…», «когда основан…», «сколько стоит… сейчас» — только при «Включаться само».
//      Это вопросы о внешних фактах; болтовня и вопросы к самой NEKO/ARIA («как дела», «кто тебя создал») сюда не попадают.
//   3. Сама модель: если она не уверена, то отвечает служебной строкой [[WEB: запрос]] (правило в системном промпте),
//      и чат делает поиск и просит её ответить ещё раз. Разбор этой строки — parseWebSentinel.

import { cleanQuery } from '@shared/services/webSearch'

export interface WebRoute {
  mode: 'explicit' | 'auto'
  query: string
  /** Спрашивать Википедию */
  wiki: boolean
  /** Спрашивать поисковик */
  web: boolean
}

/** \b в JS не работает с кириллицей — границы слов делаем через \p{L} */
const w = (src: string, flags = 'iu') => new RegExp(`(?<![\\p{L}\\d])(?:${src})(?![\\p{L}\\d])`, flags)

const SEARCH_VERB = '(?:найди|найти|найдёшь|найдешь|поищи|поискать|поищешь|искать|ищи|загугли|погугли|гугли|посмотри|проверь|узнай|выясни|разузнай|пробей)'
const GOOGLE_VERB = '(?:загугли|погугли|гугли)'
const B = '(?<![\\p{L}\\d])'
const E = '(?![\\p{L}\\d])'
const NET_PLACE = `${B}(?:(?:в|через|по)\\s+(?:интернет\\p{L}*|сети|гугл\\p{L}*|google|поиск\\p{L}*|инет\\p{L}*|нет\\p{L}*|яндекс\\p{L}*|duckduckgo)|из\\s+(?:интернета|сети)|онлайн)${E}`
const WIKI_PLACE = `${B}(?:(?:в|по|из|на)\\s+)?(?:википеди\\p{L}*|вики${E})`
const INFO_NOUN = '(?:информаци\\p{L}*|инфу|инфа|данные|сведения|подробности)'

const RE = {
  verbStart: new RegExp(`^(?:(?:ну|а|и|слушай|пожалуйста|будь добра|будь добр|плиз)[,\\s]+)*(?:ты\\s+)?(?:можешь|можешь ли ты|не могла бы ты|не мог бы ты)?\\s*${SEARCH_VERB}(?![\\p{L}\\d])`, 'iu'),
  googleVerb: w(GOOGLE_VERB),
  netPlace: new RegExp(NET_PLACE, 'iu'),
  wikiPlace: new RegExp(WIKI_PLACE, 'iu'),
  infoNoun: w(INFO_NOUN),
  // «что пишут в интернете про…», «что говорит википедия о…»
  reportVerb: w('что\\s+(?:пишут|говорят|говорит|написано|сказано|известно)'),
}

/** Слова-обёртки, которые вычищаются из запроса: «найди мне в интернете информацию про …» → «…» */
const WRAP_PLACES = [new RegExp(NET_PLACE, 'giu'), new RegExp(WIKI_PLACE, 'giu')]
const WRAP_VERB = new RegExp(`^(?:(?:ну|а|и|слушай|пожалуйста|будь добра|будь добр|плиз)[,\\s]+)*(?:ты\\s+)?(?:можешь|можешь ли ты|не могла бы ты|не мог бы ты)?\\s*${SEARCH_VERB}(?![\\p{L}\\d])\\s*`, 'iu')
const WRAP_REPORT = w('что\\s+(?:пишут|говорят|говорит|написано|сказано|известно)', 'giu')
const WRAP_FILLER = w('мне|пожалуйста|плиз|быстро|быстренько|кстати', 'giu')
const LEAD_TOPIC = new RegExp(`^(?:${INFO_NOUN}\\s*)?(?:(?:про|о|об|обо|насчёт|насчет|по\\s+теме|касательно|на\\s+тему)\\s+)?`, 'iu')

/** Вопросы к самой NEKO/ARIA и болтовня — интернет тут не нужен */
const PERSONAL = w(
  'ты|тебя|тебе|тобой|тобою|я|меня|мне|мной|мы|нас|нам|нами|вы|вас|вам|вами|' +
    '(?:тво|мо|сво)(?:й|я|ё|е|и|его|ей|ему|им|их|ю|ём|ими|ем)|нашe?\\p{L}*|ваш\\p{L}*|себя|себе|собой|нейко|неко|нэко|ария|ариа|aria|neko'
)
const CHITCHAT = new RegExp(
  '^(?:а\\s+|ну\\s+|и\\s+)?(?:как\\s+(?:дела|ты|жизнь|настроение|прошёл|прошел|спалось|погода)|чем\\s+занима|что\\s+делаешь|что\\s+нового|что\\s+случилось\\s+у)',
  'iu'
)

const QUESTION_WORD = w('кто|что|когда|где|сколько|какой|какая|какое|какие|каков|какова|почему|зачем|как|чей|куда|откуда|который|которая')

/** Вежливые «вводные» в начале вопроса: «а скажи, …», «слушай, …» */
const LEAD = '(?:(?:а|и|ну|слушай|скажи|подскажи|объясни|пожалуйста)[,\\s]+)*'
const LEAD_RE = new RegExp(`^${LEAD}`, 'iu')
const fp = (src: string) => new RegExp(`^${LEAD}${src}$`, 'iu')

interface FactPattern {
  re: RegExp
  /** Группа 1 — сама тема: в запрос идёт только она («кто такой Эйнштейн» → «Эйнштейн»), а не весь вопрос */
  subject?: boolean
  /** После ключевых слов обязательно должно идти продолжение («кто выиграл» без «чего» — не вопрос о фактах) */
  needObject?: boolean
}

/** Вопросы о внешних фактах (энциклопедические) — Википедия + поиск */
const FACT_PATTERNS: FactPattern[] = [
  // кто такой Х / что такое Х / что значит Х / что за Х
  { re: fp('(?:кто\\s+так(?:ой|ая|ое|ие)|что\\s+так(?:ое|ие)|что\\s+(?:значит|означает)|что\\s+за|кто\\s+(?:был|была|были))\\s+(.+)'), subject: true },
  // когда родился / основан / вышел…
  { re: fp('когда\\s+(?:был(?:а|о|и)?\\s+)?(?:родил(?:ся|ась|ись)|умер(?:ла|ли)?|основан(?:а|о|ы)?|созда(?:н|на|но|ны|л|ла)|вышел|вышла|вышло|вышли|выйдет|выйдут|началась|началось|закончилась|закончился|появил(?:ся|ась|ось|ись)|построен(?:а|о|ы)?|изобрели|открыли|открыт(?:а|о|ы)?|состоится|прошёл|прошел|прошла|случил(?:ся|ась|ось))\\s+(.+)') },
  // где находится…
  { re: fp('где\\s+(?:находится|находятся|расположен(?:а|о|ы)?|проходит|проходил(?:а|о|и)?)\\s+(.+)') },
  // сколько лет / жителей / стоит…
  { re: fp('сколько\\s+(?:сейчас\\s+)?(?:лет|жителей|людей|населения|стоит|стоят|весит|весят|длится|длятся|километров|метров|градусов|человек)\\s+(.+)') },
  // кто выиграл / написал / создал / изобрёл…
  { re: fp('кто\\s+(?:выиграл(?:а|и)?|победил(?:а|и)?|написал(?:а|и)?|создал(?:а|и)?|изобр[её]л(?:а|и)?|снял(?:а|и)?|основал(?:а|и)?|придумал(?:а|и)?|открыл(?:а|и)?|играет|играл(?:а|и)?|озвучивает|озвучил(?:а|и)?|является|сейчас|автор|режиссёр|режиссер|президент|премьер|директор|глава)\\s+(.+)'), needObject: true },
  // какая столица / население / площадь…
  { re: fp('(?:какая|какой|какое|каково|какова)\\s+(?:столица|население|площадь|высота|глубина|длина|официальн\\p{L}+\\s+язык\\p{L}*|валюта)\\s+(.+)') },
  // как называется / как зовут…
  { re: fp('как\\s+(?:называется|назывался|называлась|называли)\\s+(.+)') },
  // что ты знаешь про Х
  { re: fp('(?:что\\s+(?:ты\\s+)?знаешь\\s+(?:про|о|об|обо)|знаешь\\s+(?:ли\\s+ты\\s+)?(?:что-нибудь\\s+|что-то\\s+)?(?:про|о|об|обо))\\s+(.+)'), subject: true },
  // расскажи про Х
  { re: fp('(?:расскажи|расскажите|поведай)\\s+(?:мне\\s+)?(?:про|о|об|обо)\\s+(.+)'), subject: true },
]

/** Вопросы про «сейчас»: курсы, цены, результаты, релизы — энциклопедия тут устарела, идём только в поиск */
const FRESH_PATTERNS: RegExp[] = [
  /(?:курс\s+(?:доллар|евро|биткоин|рубл|юан|валют|эфир|тенге|гривн)\p{L}*|(?:доллар|евро|биткоин|юан)\p{L}*\s+(?:сегодня|сейчас|к\s+рублю))/iu,
  /(?:сколько\s+стоит|какая\s+цена|цена\s+(?:на|у))\s+.+(?:сейчас|сегодня|в\s+этом\s+году|2\d{3})/iu,
  /(?:кто\s+(?:выиграл|победил)|какой\s+счёт|какой\s+счет|результат\w*\s+(?:матч|игр|гонк|выбор|финал|турнир)\p{L}*)\s*.*(?:вчера|сегодня|последн\p{L}+|прошедш\p{L}+|в\s+20(?:2[5-9]|[3-9]\d)|20(?:2[5-9]|[3-9]\d))/iu,
  /(?:когда\s+(?:выйдет|выйдут|выходит|будет\s+релиз)|дата\s+выхода|дата\s+релиза)\s+.+/iu,
  /(?:что\s+(?:сейчас\s+)?(?:происходит|случилось|произошло|нового)\s+(?:в\s+мире|в\s+стране|в\s+\p{L}+|с\s+\p{L}+)|последние\s+новости\s+(?:про|о|об))\s*.*/iu,
  /(?:последн(?:яя|ий|ее|ие)\s+верси\p{L}*|актуальн(?:ая|ый|ое|ые)\s+верси\p{L}*|свежая\s+верси\p{L}*)\s+.+/iu,
]

const trimEnd = (s: string) => s.replace(/[\s?!.…,;:]+$/g, '').trim()

/** Из «найди мне в интернете информацию про котов» оставляет «котов» */
export function extractWebQuery(text: string): string {
  let q = text.trim()
  for (const re of WRAP_PLACES) q = q.replace(re, ' ')
  q = q.replace(/\s+/g, ' ').trim().replace(/^[,.:;\-–—\s]+/, '')
  q = q.replace(WRAP_VERB, '').replace(WRAP_REPORT, ' ').replace(WRAP_FILLER, ' ')
  q = q.replace(/\s+/g, ' ').trim().replace(/^[,.:;\-–—\s]+/, '')
  q = q.replace(/^(?:а\s+)?что\s+(?:там\s+)?(?:(?:есть|написано|известно)\s+)?(?=(?:про|о|об|обо)\s)/iu, '')
  q = q.replace(LEAD_TOPIC, '').trim()
  // «кто такой Х» после явной команды: оставляем сам Х
  q = q.replace(/^(?:кто\s+так(?:ой|ая|ое|ие)|что\s+так(?:ое|ие))\s+/iu, '')
  return cleanQuery(trimEnd(q))
}

const MAX_EXPLICIT = 300
const MAX_AUTO = 160

/**
 * Решает, нужен ли интернет для этого сообщения. null — не нужен (обычный ответ модели).
 * @param opts.auto  включена ли эвристика «сам»; явные просьбы работают независимо от неё
 */
export function routeWeb(input: string, opts: { auto: boolean }): WebRoute | null {
  const text = input.trim()
  if (!text || text.length > MAX_EXPLICIT) return null

  /* 1. Явная просьба */
  const hasWiki = RE.wikiPlace.test(text)
  const hasNet = RE.netPlace.test(text)
  const verb = RE.verbStart.test(text)
  const google = RE.googleVerb.test(text)
  const report = RE.reportVerb.test(text)

  const explicit =
    google ||
    (verb && (hasNet || hasWiki || RE.infoNoun.test(text))) ||
    (report && (hasNet || hasWiki)) ||
    (hasWiki && (verb || QUESTION_WORD.test(text) || /^(?:вики|википеди)/iu.test(text)))
  if (explicit) {
    const query = extractWebQuery(text)
    if (query.length < 2 || /^(?:а\s+)?(?:что|кто|это|то|что-нибудь|что-то|ответ)(?:\s+(?:такое|такой|это|за))?$/iu.test(query)) return null
    // «в википедии X» — спрашивали именно энциклопедию; «в интернете X» — оба источника
    const wikiOnly = hasWiki && !hasNet && !google
    return { mode: 'explicit', query, wiki: true, web: !wikiOnly }
  }

  /* 2. Эвристика по форме вопроса */
  if (!opts.auto || text.length > MAX_AUTO) return null
  if (CHITCHAT.test(text)) return null

  const body = text.replace(/^[\s"«]+/, '')

  for (const re of FRESH_PATTERNS) {
    if (!re.test(body) || PERSONAL.test(body)) continue
    if (!QUESTION_WORD.test(body) && !/[?]\s*$/.test(body) && !/^(?:курс|цена|последн)/iu.test(body)) continue
    const query = cleanQuery(trimEnd(body.replace(LEAD_RE, '')))
    return query.length >= 3 ? { mode: 'auto', query, wiki: false, web: true } : null
  }

  for (const { re, subject, needObject } of FACT_PATTERNS) {
    const m = re.exec(body)
    if (!m) continue
    const topic = trimEnd(m[1] ?? '')
    if (PERSONAL.test(topic)) return null // вопрос про саму NEKO/ARIA или собеседника
    if (topic.length < 2 && (needObject || subject)) return null
    if (topic.split(/\s+/).filter(Boolean).length > 8) return null // длинная «простыня» — это не справочный вопрос
    // Для «кто такой Х» и «расскажи о Х» в поиск уходит сама тема, для «когда/где/сколько» — весь вопрос: уточнения важны
    const q = subject ? cleanQuery(topic) : cleanQuery(trimEnd(body.replace(LEAD_RE, '')))
    return q.length >= 2 ? { mode: 'auto', query: q, wiki: true, web: true } : null
  }

  return null
}

/* ───────────────────────── Запрос от самой модели ───────────────────────── */

const SENTINEL_WORDS = ['WEB', 'SEARCH', 'ПОИСК', 'ИНТЕРНЕТ']
const SENTINEL = /^\s*\[{1,2}\s*(?:WEB|SEARCH|ПОИСК|ИНТЕРНЕТ)\s*[:：=]\s*([^\]\n]{2,200}?)\s*(?:\]{1,2}|$)/iu

/** Если ответ модели — это просьба «найди в интернете», возвращает поисковый запрос */
export function parseWebSentinel(text: string): string | null {
  const m = SENTINEL.exec(text)
  if (!m) return null
  const q = cleanQuery(m[1])
  return q.length >= 2 ? q : null
}

/**
 * Решение «о чём этот поток»: пока модель не написала ни одного видимого символа, текст придерживается.
 *   'wait' — рано судить (началось с «[» и похоже на служебную строку, а скобка ещё не закрыта)
 *   'text' — это обычный ответ, можно показывать и озвучивать
 *   { query } — это просьба поиска, показывать нельзя
 */
export function judgeStreamHead(head: string, final = false): 'wait' | 'text' | { query: string } {
  const t = head.trimStart()
  if (!t) return final ? 'text' : 'wait'
  if (t[0] !== '[') return 'text'
  const query = parseWebSentinel(t)
  if (query && (final || t.includes(']'))) return { query }
  if (final || t.includes(']') || t.length > 220) return 'text' // скобки закрыты, но это не поиск — обычный текст
  // Скобка ещё не закрыта: ждём, только если начало похоже на служебную строку («[», «[[W», «[[WEB: курс дол»)
  const after = t.replace(/^\[+\s*/, '').toUpperCase()
  const looksLikeSentinel = after === '' || SENTINEL_WORDS.some((k) => k.startsWith(after) || after.startsWith(k))
  return looksLikeSentinel ? 'wait' : 'text'
}
