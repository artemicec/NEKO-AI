/**
 * Срабатывает только на короткие явные просьбы вроде «расскажи факт», «цитату дня», «случайный факт».
 * (Раньше плагин перехватывал любое сообщение со словом «факт» — например «фактически», «какой факт ты знаешь про…».)
 */
const FACT_REQUEST =
  /^(?:(?:ну\s+)?(?:пожалуйста[,\s]*)?(?:расскажи|скажи|дай|покажи|хочу|давай|можно)\s+(?:мне\s+)?)?(?:(?:какой[-\s]нибудь|какую[-\s]нибудь|случайный|случайную|интересный|интересную|новый|новую|любой|любую|свежий|свежую)\s+)*(?:факт|цитат[ауы]|факт\s+дня|цитат[ауы]\s+дня)(?:\s+(?:дня|пожалуйста))?[\s?!.]*$/iu

export class FactPlugin implements Plugin {
  name = 'Случайный факт'
  description = 'Интересный факт или цитата'
  icon = '💡'

  matches(input: string): boolean {
    const t = input.trim()
    return t.length <= 60 && FACT_REQUEST.test(t)
  }

  async execute(input: string): Promise<string> {
    if (!this.matches(input)) return ''
    const daily = /дня/i.test(input)
    const fact = daily ? this.getDailyFact() : this.getRandomFact()
    return `💡 Знаешь ли ты?\n\n${fact}\n\n*Ня~ Всегда есть что-то новое!* ✨`
  }

  // Метод для получения случайного факта без проверки команды (для стартового сообщения)
  getRandomFact(): string {
    return facts[Math.floor(Math.random() * facts.length)]
  }

  getDailyFact(): string {
    // Используем текущую дату как seed
    const seed = new Date().toDateString()
    let hash = 0
    for (let i = 0; i < seed.length; i++) {
      hash = seed.charCodeAt(i) + ((hash << 5) - hash)
    }
    return facts[Math.abs(hash) % facts.length]
  }
}
